'use strict';

// Builds the master-template bundle: every backend/*.gs joined in file-name order into
// one Code.gs (Apps Script runs all files in one global scope in that order) plus
// appsscript.json. Use it to create or rebuild the Google Sheet template without clasp:
// paste Code.gs into the Apps Script editor and replace appsscript.json.
// Output: dist-template/ (git-ignored).

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { execFileSync } = require('node:child_process');

const ROOT = path.join(__dirname, '..');
const BACKEND = path.join(ROOT, 'backend');

function commitId() {
  try {
    return execFileSync('git', ['rev-parse', '--short=7', 'HEAD'], {
      cwd: ROOT,
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .toString()
      .trim();
  } catch {
    return 'unknown';
  }
}

function buildTemplate(options = {}) {
  const outDir = options.outDir || path.join(ROOT, 'dist-template');
  const commit = options.commit || commitId();
  const files = fs
    .readdirSync(BACKEND)
    .filter((name) => name.endsWith('.gs'))
    .sort();
  if (files.length === 0) throw new Error('No backend/*.gs files found.');

  const parts = files.map(
    (name) =>
      '// ===== backend/' + name + ' =====\n' + fs.readFileSync(path.join(BACKEND, name), 'utf8'),
  );
  const code =
    '// Cash Voucher master template bundle. Source commit: ' +
    commit +
    '\n// Generated by scripts/build-template.js. Do not edit by hand; rebuild from the repository.\n\n' +
    parts.join('\n');

  // Fail here, not in a customer's editor, if the joined file cannot be parsed.
  new vm.Script(code, { filename: 'Code.gs' });

  const manifest = fs.readFileSync(path.join(BACKEND, 'appsscript.json'), 'utf8');
  JSON.parse(manifest);

  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'Code.gs'), code, 'utf8');
  fs.writeFileSync(path.join(outDir, 'appsscript.json'), manifest, 'utf8');
  fs.writeFileSync(
    path.join(outDir, 'BUILD.txt'),
    'Commit: ' +
      commit +
      '\nFiles joined (' +
      files.length +
      '): ' +
      files.join(', ') +
      '\nUse: paste Code.gs into the Apps Script editor (one file named Code), and replace appsscript.json.\nDo not run setup() or deploy in the master template.\n',
    'utf8',
  );
  return { outDir, commit, files, bytes: Buffer.byteLength(code) };
}

if (require.main === module) {
  const result = buildTemplate();
  console.log(
    'Template bundle OK — ' +
      result.files.length +
      ' backend files joined, commit ' +
      result.commit +
      ', ' +
      result.bytes +
      ' bytes → ' +
      path.relative(ROOT, result.outDir) +
      '/',
  );
}

module.exports = { buildTemplate };
