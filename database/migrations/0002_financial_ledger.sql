CREATE TABLE IF NOT EXISTS vouchers (
    id CHAR(36) NOT NULL PRIMARY KEY,
    voucher_type VARCHAR(12) NOT NULL,
    voucher_number VARCHAR(32) NOT NULL,
    business_date DATE NOT NULL,
    vendor_name_snapshot VARCHAR(200) NOT NULL,
    vendor_id CHAR(36) NULL,
    vendor_type VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED',
    amount_paise BIGINT NOT NULL,
    category VARCHAR(80) NOT NULL,
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    cash_impact VARCHAR(16) NOT NULL DEFAULT 'UNCLASSIFIED',
    approval_status VARCHAR(20) NOT NULL DEFAULT 'NOT_REQUIRED',
    approval_reason VARCHAR(200) NOT NULL DEFAULT '',
    payment_method VARCHAR(20) NOT NULL DEFAULT '',
    cancel_reason VARCHAR(200) NOT NULL DEFAULT '',
    client_id VARCHAR(128) NULL,
    source_legacy_id VARCHAR(128) NULL,
    created_by_user_id CHAR(36) NULL,
    created_by_email_snapshot VARCHAR(254) NOT NULL DEFAULT '',
    updated_by_user_id CHAR(36) NULL,
    approved_by_user_id CHAR(36) NULL,
    created_at_utc DATETIME(6) NOT NULL,
    updated_at_utc DATETIME(6) NOT NULL,
    approved_at_utc DATETIME(6) NULL,
    UNIQUE KEY uq_vouchers_type_number (voucher_type, voucher_number),
    UNIQUE KEY uq_vouchers_client_id (client_id),
    UNIQUE KEY uq_vouchers_legacy_id (source_legacy_id),
    KEY ix_vouchers_business_date_status (business_date, status),
    KEY ix_vouchers_creator_date (created_by_user_id, business_date),
    KEY ix_vouchers_vendor_date (vendor_id, business_date),
    KEY ix_vouchers_approval_date (approval_status, business_date),
    CONSTRAINT fk_vouchers_vendor FOREIGN KEY (vendor_id) REFERENCES vendors (id),
    CONSTRAINT fk_vouchers_creator FOREIGN KEY (created_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_vouchers_updater FOREIGN KEY (updated_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_vouchers_approver FOREIGN KEY (approved_by_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS voucher_approval_events (
    id CHAR(36) NOT NULL PRIMARY KEY,
    voucher_id CHAR(36) NOT NULL,
    decision VARCHAR(16) NOT NULL,
    previous_status VARCHAR(20) NOT NULL,
    next_status VARCHAR(20) NOT NULL,
    reason VARCHAR(200) NOT NULL DEFAULT '',
    actor_user_id CHAR(36) NOT NULL,
    occurred_at_utc DATETIME(6) NOT NULL,
    KEY ix_approval_events_voucher_time (voucher_id, occurred_at_utc),
    CONSTRAINT fk_approval_events_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers (id),
    CONSTRAINT fk_approval_events_actor FOREIGN KEY (actor_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS voucher_receipts (
    id CHAR(36) NOT NULL PRIMARY KEY,
    voucher_id CHAR(36) NOT NULL,
    storage_key VARCHAR(255) NULL,
    legacy_drive_file_id VARCHAR(160) NULL,
    content_type VARCHAR(80) NOT NULL,
    byte_size BIGINT UNSIGNED NOT NULL,
    sha256 CHAR(64) NOT NULL,
    created_by_user_id CHAR(36) NULL,
    created_at_utc DATETIME(6) NOT NULL,
    UNIQUE KEY uq_receipts_storage_key (storage_key),
    UNIQUE KEY uq_receipts_legacy_drive_id (legacy_drive_file_id),
    KEY ix_receipts_voucher (voucher_id),
    CONSTRAINT fk_receipts_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers (id),
    CONSTRAINT fk_receipts_creator FOREIGN KEY (created_by_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cash_closes (
    id CHAR(36) NOT NULL PRIMARY KEY,
    business_date DATE NOT NULL,
    drawer_key VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    opening_cash_paise BIGINT NOT NULL,
    opening_source VARCHAR(24) NOT NULL,
    opening_close_id CHAR(36) NULL,
    opening_reason VARCHAR(200) NOT NULL DEFAULT '',
    cash_in_total_paise BIGINT NOT NULL,
    cash_out_total_paise BIGINT NOT NULL,
    expected_cash_paise BIGINT NOT NULL,
    counted_cash_paise BIGINT NOT NULL,
    variance_paise BIGINT NOT NULL,
    variance_reason VARCHAR(200) NOT NULL DEFAULT '',
    included_voucher_count INT UNSIGNED NOT NULL,
    included_voucher_ids JSON NOT NULL,
    included_voucher_snapshot JSON NOT NULL,
    created_by_user_id CHAR(36) NOT NULL,
    created_at_utc DATETIME(6) NOT NULL,
    time_zone VARCHAR(64) NOT NULL DEFAULT 'Asia/Kolkata',
    request_id VARCHAR(128) NOT NULL,
    request_payload_hash CHAR(64) NOT NULL,
    UNIQUE KEY uq_cash_closes_date_drawer (business_date, drawer_key),
    UNIQUE KEY uq_cash_closes_request (request_id),
    KEY ix_cash_closes_created_at (created_at_utc),
    CONSTRAINT fk_cash_closes_previous FOREIGN KEY (opening_close_id) REFERENCES cash_closes (id),
    CONSTRAINT fk_cash_closes_creator FOREIGN KEY (created_by_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cash_close_corrections (
    id CHAR(36) NOT NULL PRIMARY KEY,
    cash_close_id CHAR(36) NOT NULL,
    business_date DATE NOT NULL,
    voucher_id CHAR(36) NULL,
    correction_type VARCHAR(24) NOT NULL,
    details VARCHAR(500) NOT NULL DEFAULT '',
    reason VARCHAR(200) NOT NULL,
    created_by_user_id CHAR(36) NOT NULL,
    created_at_utc DATETIME(6) NOT NULL,
    KEY ix_cash_close_corrections_close_time (cash_close_id, created_at_utc),
    KEY ix_cash_close_corrections_voucher (voucher_id),
    CONSTRAINT fk_cash_close_corrections_close FOREIGN KEY (cash_close_id) REFERENCES cash_closes (id),
    CONSTRAINT fk_cash_close_corrections_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers (id),
    CONSTRAINT fk_cash_close_corrections_creator FOREIGN KEY (created_by_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
