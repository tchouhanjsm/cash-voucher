CREATE TABLE IF NOT EXISTS voucher_import_batches (
    id CHAR(36) NOT NULL PRIMARY KEY,
    source_system VARCHAR(48) NOT NULL,
    source_batch_id VARCHAR(128) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    row_count INT UNSIGNED NOT NULL,
    imported_count INT UNSIGNED NOT NULL DEFAULT 0,
    replayed_count INT UNSIGNED NOT NULL DEFAULT 0,
    quarantined_count INT UNSIGNED NOT NULL DEFAULT 0,
    pending_count INT UNSIGNED NOT NULL DEFAULT 0,
    source_total_paise BIGINT UNSIGNED NOT NULL DEFAULT 0,
    imported_total_paise BIGINT UNSIGNED NOT NULL DEFAULT 0,
    quarantined_total_paise BIGINT UNSIGNED NOT NULL DEFAULT 0,
    pending_total_paise BIGINT UNSIGNED NOT NULL DEFAULT 0,
    variance_paise BIGINT NOT NULL DEFAULT 0,
    created_by_user_id CHAR(36) NOT NULL,
    created_at_utc DATETIME(6) NOT NULL,
    updated_at_utc DATETIME(6) NOT NULL,
    UNIQUE KEY uq_voucher_import_source_batch (source_system, source_batch_id),
    KEY ix_voucher_import_batch_creator_time (created_by_user_id, created_at_utc),
    CONSTRAINT fk_voucher_import_batch_creator FOREIGN KEY (created_by_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS voucher_import_rows (
    id CHAR(36) NOT NULL PRIMARY KEY,
    batch_id CHAR(36) NOT NULL,
    source_record_id VARCHAR(100) NOT NULL,
    source_legacy_id VARCHAR(128) NOT NULL,
    source_row_number INT UNSIGNED NOT NULL,
    row_sha256 CHAR(64) NOT NULL,
    voucher_type VARCHAR(12) NULL,
    source_amount_paise BIGINT UNSIGNED NULL,
    status VARCHAR(16) NOT NULL,
    voucher_id CHAR(36) NULL,
    error_code VARCHAR(80) NULL,
    error_message VARCHAR(300) NULL,
    attempted_count INT UNSIGNED NOT NULL DEFAULT 0,
    created_at_utc DATETIME(6) NOT NULL,
    updated_at_utc DATETIME(6) NOT NULL,
    UNIQUE KEY uq_voucher_import_batch_record (batch_id, source_record_id),
    KEY ix_voucher_import_legacy_hash (source_legacy_id, row_sha256),
    KEY ix_voucher_import_batch_status (batch_id, status, source_row_number),
    KEY ix_voucher_import_voucher (voucher_id),
    CONSTRAINT fk_voucher_import_row_batch FOREIGN KEY (batch_id) REFERENCES voucher_import_batches (id),
    CONSTRAINT fk_voucher_import_row_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
